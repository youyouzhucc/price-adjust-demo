function setHero(r, i) {
  state.hero = (i + r.photos.length) % r.photos.length;
  const p = r.photos[state.hero];
  const slide = document.querySelector(".hero-slide");
  if (!slide) return;
  slide.style.backgroundImage = `url('${p.src}')`;
  slide.dataset.src = p.src;
  slide.dataset.cap = p.cap;
  $("hero-count").textContent = `${state.hero + 1}/${r.photos.length}`;
  document.querySelectorAll(".hero-dots span").forEach((el, idx) => {
    el.classList.toggle("is-on", idx === state.hero);
  });
}


function chips(el, items, key, labelOf = (x) => x) {
  el.innerHTML = items
    .map((item) => {
      const id = item.id || item;
      const label = item.label || labelOf(item);
      return `<button type="button" class="chip${state[key] === id ? " is-on" : ""}" data-key="${key}" data-id="${id}">${label}</button>`;
    })
    .join("");
}

function match(route) {
  if (state.style && !route.styles.includes(state.style)) return false;
  if (state.scenery && !route.scenery.includes(state.scenery)) return false;
  if (state.area && route.area !== state.area) return false;
  if (state.level && String(route.level) !== state.level) return false;
  return true;
}


function showBrowse() {
  if (mapInst) {
    mapInst.remove();
    mapInst = null;
  }
  $("detail").hidden = true;
  $("foot").hidden = false;
  $("browse").hidden = false;
  renderList();
}

function onHash() {
  const id = decodeURIComponent(location.hash.replace(/^#/, ""));
  if (id) renderDetail(id);
  else showBrowse();
}

document.addEventListener("click", (e) => {
  const chip = e.target.closest(".chip");
  if (chip) {
    const { key, id } = chip.dataset;
    state[key] = state[key] === id ? "" : id;
    renderList();
    return;
  }
  const lite = e.target.closest("[data-lite]");
  if (lite) {
    openLite(lite.dataset.lite, lite.dataset.cap);
    return;
  }
  if (e.target.closest(".lightbox-close") || e.target.id === "lightbox") {
    $("lightbox").hidden = true;
    return;
  }
  const card = e.target.closest("[data-open]");
  if (card) location.hash = card.dataset.open;
});

onHash();
